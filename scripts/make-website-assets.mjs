// Builds apps/server/src/website/assets.ts: the fonts (SIL Open Font License, latin subsets from the
// @fontsource-variable packages) and the icons (lucide, ISC licence) a website Neddy builds can use,
// as one module so the api's compiled output carries them. Run it again after changing the lists.
//
//   node scripts/make-website-assets.mjs <folder holding the unpacked fontsource packages>
// (npm pack @fontsource-variable/outfit etc. and untar each into <folder>/<package>/package)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FONT_DIR = process.argv[2];
if (!FONT_DIR) throw new Error("Give the folder with the unpacked fontsource packages");

/** Family name, package folder prefix, file stem, what it is good for. */
const FONTS = [
  ["Outfit", "outfit", "outfit", "heading", "Geometric and friendly; strong headings"],
  ["Plus Jakarta Sans", "plus-jakarta-sans", "plus-jakarta-sans", "body", "Clear, modern text"],
  ["Inter", "inter", "inter", "body", "Neutral, very readable"],
  ["Manrope", "manrope", "manrope", "both", "Crisp and slightly technical"],
  ["DM Sans", "dm-sans", "dm-sans", "both", "Warm and rounded"],
  ["Fraunces", "fraunces", "fraunces", "heading", "A characterful serif for headings"],
];
const fonts = {};
for (const [family, pkg, stem] of FONTS) {
  const file = join(
    FONT_DIR,
    `fontsource-variable-${pkg}-5.3.0`,
    "package",
    "files",
    `${stem}-latin-wght-normal.woff2`,
  );
  fonts[family] = readFileSync(file).toString("base64");
}

