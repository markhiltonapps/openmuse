const icons = {};
for (const name of ICONS) {
  const source = readFileSync(
    join(ROOT, "apps/mobile/node_modules/lucide-react-native/dist/esm/icons", `${name}.js`),
    "utf8",
  );
  const nodes = [
    ...source.matchAll(
      /\[\s*"(path|circle|rect|line|polyline|polygon|ellipse)",\s*\{([\s\S]*?)\}\s*\]/g,
    ),
  ];
  if (!nodes.length) throw new Error(`No shapes found in ${name}`);
  icons[name] = nodes
    .map(([, tag, body]) => {
      const attrs = [...body.matchAll(/(\w+):\s*"([^"]*)"/g)]
        .filter(([, key]) => key !== "key")
        .map(
          ([, key, value]) => `${key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}="${value}"`,
        )
        .join(" ");
      return `<${tag} ${attrs}/>`;
    })
    .join("");
}

